def gh_slug(text: str) -> str:
    """Heading id the way GitHub makes it."""
    s = re.sub(r"<[^>]+>", "", text).strip().lower()
    s = re.sub(r"[^\w\- ]", "", s)
    return s.replace(" ", "-")


def render(handle: str, cfg: dict) -> str:
    src = (ROOT / "README.md").read_text()
    body = markdown.markdown(src, extensions=["tables"])

    # <picture> → <img> carrying both sources so the toggle can swap them.
    def pic(m):
        dark, inner = m.group(1), m.group(2)
        light = re.search(r'src="([^"]+)"', inner).group(1)
        rest = re.sub(r'\s*src="[^"]+"', "", inner)
        return f'<img data-dark="{dark}" data-light="{light}" src="{dark}"{rest[4:]}'
    body = re.sub(r'<picture><source media="\(prefers-color-scheme: dark\)" srcset="([^"]+)">(<img[^>]*>)</picture>',
                  pic, body)

    body = re.sub(r'<p align="center"><img data-dark="https://raw\.githubusercontent\.com[^"]*/output/snake[^>]*></p>',
                  SNAKE_PLACEHOLDER, body)
    body = body.replace('="assets/', '="../assets/')
    # The live view counter would count every local reload: show a stand-in.
    body = re.sub(r'https://komarev\.com/ghpvc/\?[^"]*',
                  "https://img.shields.io/badge/Profile%20views-counts%20after%20push-34d399?style=flat-square", body)
    body = re.sub(r"<(h[23])>(.*?)</\1>", lambda m: f'<{m.group(1)} id="{gh_slug(m.group(2))}">{m.group(2)}</{m.group(1)}>', body)
    body = body.replace('<p align="center">', '<p style="text-align:center">')
    return PAGE.format(handle=handle, name=cfg.get("name") or handle,
                       location=cfg.get("location") or "", body=body)


class Handler(http.server.SimpleHTTPRequestHandler):
    def do_GET(self):
        if self.path in ("/", "/index.html"):
            self.send_response(302)
            self.send_header("Location", "/preview/")
            self.end_headers()
            return
        super().do_GET()

    def end_headers(self):
        self.send_header("Cache-Control", "no-store")
        super().end_headers()

    def log_message(self, *a):
        pass


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-build", action="store_true")
    ap.add_argument("--no-serve", action="store_true")
    ap.add_argument("--port", type=int, default=8000)
    args = ap.parse_args()

    if not args.no_build:
        subprocess.run([sys.executable, str(ROOT / "scripts" / "build.py")], check=True)
    cfg = yaml.safe_load((ROOT / "profile.yml").read_text()) or {}
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(render(cfg.get("handle", ""), cfg))
    print(f"  ✓ {OUT.relative_to(ROOT)}")
    if args.no_serve:
        return 0
    print(f"Serving on http://localhost:{args.port}  (Ctrl+C to stop)")
    http.server.ThreadingHTTPServer(("127.0.0.1", args.port),
                                    functools.partial(Handler, directory=str(ROOT))).serve_forever()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
